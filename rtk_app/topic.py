"""
Проверка, относится ли вопрос пользователя к геодезии и RTK-поправкам.
"""
from .deepseek import ask_deepseek_raw

# Ключевые слова для быстрой проверки темы (англ., рус., транслит).
# Охватывается геодезия в широком смысле + RTK/GNSS-поправки.
TOPIC_KEYWORDS = [
    # геодезия (рус. / англ.)
    "геодез", "нивелир", "нивелирн", "теодолит", "тахеометр", "топограф",
    "нивелирован", "полигонометр", "триангуляц", "геоид", "репер",
    "кадастр", "межеван", "survey", "geodesy", "землеустройств",
    # спутниковая геодезия и навигация
    "rtk", "rtcm", "gnss", "gps", "глонасс", "глонас", "glonass", "galileo",
    "cmr", "msm", "спутник", "сателлит", "эфемерид",
    # поправки / дифференциальная навигация
    "поправк", "поправка", "коррекц", "цмр", "ртцм", "ртк", "гнсс",
    "базовые станции", "базовая станция", "референц",
    # измерения и координаты
    "координат", "план", "высот", "широт", "долгот", "фазовые наблюдения",
    "псевдодальност", "дифференциальн", "точност",
]


def contains_topic_keyword(question):
    """Быстрая проверка по ключевым словам (учитывает регистр, рус., транслит)."""
    q = question.lower()
    return any(kw in q for kw in TOPIC_KEYWORDS)


def is_related_to_rtk(api_key, question):
    """Определяет, относится ли вопрос к геодезии и RTK-поправкам.

    Сначала — быстрая проверка по ключевым словам, затем, при их отсутствии —
    уточняющая проверка через DeepSeek. При ошибке считаем вопрос подходящим
    (возвращаем True), чтобы не блокировать запуск.
    """
    # 1) Быстрая проверка по ключевым словам (включая русские/транслит)
    if contains_topic_keyword(question):
        return True

    # 2) Если слов не нашлось — спрашиваем DeepSeek (учитывает синонимы/смысл)
    system_content = (
        "Ты — модератор тем. Определи, относится ли вопрос пользователя к ГЕОДЕЗИИ "
        "и связанным с ней темам: RTK-поправки (RTK, RTCM, GNSS, GPS, ГЛОНАСС, CMR, "
        "MSM), работа с базовыми/референц-станциями, эфемериды, координаты, "
        "нивелирование, топография, кадастр, геодезические измерения и оборудование "
        "(тахеометр, теодолит, нивелир) и т.п. Учитывай русские и транслит-варианты "
        "названий (например, ЦМР = CMR, РТЦМ = RTCM, РТК = RTK, ГНСС = GNSS). "
        "Ответь ровно одним словом: ДА (если относится) или НЕТ (если не относится)."
    )
    try:
        answer = ask_deepseek_raw(api_key, system_content, question).strip()
        return answer.upper().startswith("ДА")
    except Exception:
        # При любой ошибке — считаем вопрос подходящим, чтобы не блокировать запуск
        return True
