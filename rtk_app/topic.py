"""
Определение темы вопроса пользователя через языковую модель.

Вопрос проходит «простое уточнение» (ступень 1): классификатор определяет,
относится ли он к геодезии. Если да — основной запрос отвечает в роли.
Если нет (вопрос про другое) — используется вежливая рекомендация обратиться
к профильному специалисту соответствующей области (ступень 2). Такие
не-геодезические ходы в историю сессии не сохраняются.
"""
from .deepseek import ask_deepseek_raw

# Системный промпт для "классификатора" — определяет, по геодезии ли вопрос.
_TOPIC_SYSTEM = (
    "Ты — маршрутизатор вопросов. Определи, относится ли вопрос к геодезии "
    "и связанным с ней темам: RTK/GNSS-поправки (RTCM, CMR, MSM), базовые "
    "и референц-станции, эфемериды, координаты, нивелирование, топография, "
    "кадастр, геодезические измерения и оборудование (тахеометр, теодолит, "
    "нивелир, GNSS-приёмники) и иные смежные области геодезии. Учитывай "
    "русские и транслит-варианты названий (ЦМР=CMR, РТЦМ=RTCM, РТК=RTK, "
    "ГНСС=GNSS). Ответь строго в одном из двух форматов, без лишнего текста:\n"
    "GEO — если вопрос относится к геодезии;\n"
    "OTHER:<название области> — если вопрос НЕ относится к геодезии; "
    "вместо <название области> укажи короткую тему постороннего вопроса "
    "(например OTHER:кулинария)."
)


def classify_theme(api_key, question):
    """Определяет тему вопроса через модель (ступень 1).

    Возвращает кортеж:
      ("geo", None)            — вопрос по геодезии;
      ("other", "<область>")   — вопрос не по геодезии + распознанная тема.
    При ошибке сервиса считаем вопрос геодезическим (не блокируем диалог).
    """
    try:
        raw = ask_deepseek_raw(api_key, _TOPIC_SYSTEM, question).strip()
    except Exception:
        return ("geo", None)

    line = (raw or "").splitlines()[0].strip().upper()
    if line.startswith("GEO"):
        return ("geo", None)
    if line.startswith("OTHER:"):
        domain = raw.split(":", 1)[1].strip() if ":" in raw else ""
        return ("other", domain or "соответствующему специалисту")
    # Непредвиденный формат — не блокируем, считаем геодезией.
    return ("geo", None)


def build_redirect(api_key, question, domain):
    """Вежливая рекомендация для вопроса, не относящегося к геодезии.

    Просит модель назвать профильного специалиста по контексту постороннего
    вопроса (например кулинария → повар) и кратко это оформить.
    """
    sys_redirect = (
        "Ты — вежливый консультант геодезической службы. Вопрос пользователя "
        "относится НЕ к геодезии, а к области: {domain}.\n"
        "Сформулируй короткий вежливый ответ, в котором сообщи, что вопрос "
        "вне твоей геодезической специализации, и предложи обратиться к "
        "профильному специалисту этой области (назови его конкретно, "
        "например для кулинарии — повар/шеф-повар). 1–2 предложения."
    ).format(domain=domain)
    question_note = f"Вопрос пользователя: {question}"
    try:
        return ask_deepseek_raw(api_key, sys_redirect, question_note).strip()
    except Exception:
        return (
            "Этот вопрос, похоже, не относится к геодезии. Для точной помощи "
            "рекомендуем обратиться к профильному специалисту соответствующей "
            f"области ({domain})."
        )


